package io.elasticore.base.model.pub.rules.verify;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Compares every file the 2.x pipeline generated with the file the rule
 * engine writes in its place, one tree against the other.
 *
 * elcoreRulesCheck compares seven artifact kinds in memory. Everything else
 * the extractor writes - mappers, Q classes, repository helpers, composite
 * key classes, core services, port services - had no such check, and a kind
 * the rule engine never wrote went unnoticed because nothing asked for it.
 * This check starts from the 2.x tree instead: every file carrying the
 * generated-file header must exist in the rule engine's tree and read the
 * same.
 *
 *   TreeCheckRunner &lt;golden source root&gt; &lt;generated source root&gt;
 *
 * Exits 1 when a file is missing or differs without an accepted reason.
 */
public final class TreeCheckRunner {

    private static final String HEADER = "//ecd:";
    private static final String MARKER = "// Initially generated by ElastiCORE";

    /**
     * Files the rules deliberately write differently, and why. Keyed by the
     * path under the source root. The same decisions elcoreRulesCheck
     * accepts, said for the whole file.
     */
    static final Map<String, String> ACCEPTED;
    static {
        Map<String, String> m = new LinkedHashMap<String, String>();
        String relationFlattening =
                "2.x flattened only the first of two identically declared @ManyToOne "
                + "relations; the rules flatten both (additive search property).";
        m.put("io/elasticore/blueprint/domain/shop/dto/OrderItemSrchDTO.java", relationFlattening);
        m.put("io/elasticore/blueprint/domain/content/dto/CommentSrchDTO.java", relationFlattening);
        m.put("io/elasticore/blueprint/domain/shop/dto/ShopMapper.java", relationFlattening + " toSpec reads it.");
        m.put("io/elasticore/blueprint/domain/content/dto/ContentMapper.java", relationFlattening + " toSpec reads it.");
        ACCEPTED = Collections.unmodifiableMap(m);
    }

    public static void main(String[] args) throws IOException {
        if (args.length < 2) {
            System.out.println("usage: TreeCheckRunner <golden root> <generated root>");
            System.exit(2);
            return;
        }
        int failures = new TreeCheckRunner().run(new File(args[0]), new File(args[1]));
        if (failures > 0) System.exit(1);
    }

    /** Compares the trees, prints the report and returns the number of failures. */
    int run(File golden, File generated) throws IOException {
        Map<String, String> before = generatedFiles(golden);
        Map<String, String> after = readAll(generated);

        List<String> missing = new ArrayList<String>();
        // A generated file 2.x does not write: the rule engine writing more
        // than the model asks for is a difference too.
        List<String> extra = new ArrayList<String>();
        Map<String, String> beforeAll = readAll(golden);
        for (Map.Entry<String, String> en : after.entrySet()) {
            if (!en.getValue().startsWith(HEADER) || beforeAll.containsKey(en.getKey())) continue;
            if (en.getValue().contains("_V3.0") && !en.getValue().contains(MARKER)) extra.add(en.getKey());
        }
        List<String> differ = new ArrayList<String>();
        List<String> accepted = new ArrayList<String>();
        List<String> importOrder = new ArrayList<String>();
        Map<String, int[]> byKind = new TreeMap<String, int[]>();
        int same = 0;

        for (Map.Entry<String, String> en : before.entrySet()) {
            String path = en.getKey();
            int[] counts = byKind.get(kindOf(path));
            if (counts == null) byKind.put(kindOf(path), counts = new int[2]);
            counts[0]++;
            String other = after.get(path);
            if (other == null) {
                missing.add(path);
            } else if (normalize(en.getValue()).equals(normalize(other))) {
                same++;
                counts[1]++;
            } else if (sortedImports(en.getValue()).equals(sortedImports(other))) {
                // The same imports in another order: nothing a compiler or a
                // reader acts on, so said but not failed.
                importOrder.add(path);
                counts[1]++;
            } else if (ACCEPTED.containsKey(path)) {
                accepted.add(path + " - " + ACCEPTED.get(path));
                counts[1]++;
            } else {
                differ.add(path + firstDifference(en.getValue(), other));
            }
        }

        System.out.println("=== tree check: " + before.size() + " generated by 2.x | "
                + same + " identical | " + importOrder.size() + " import order only | "
                + accepted.size() + " accepted | "
                + differ.size() + " differ | " + missing.size() + " missing | " + extra.size() + " extra ===");
        for (Map.Entry<String, int[]> en : byKind.entrySet()) {
            System.out.println(String.format("  %-18s %3d / %3d", en.getKey(), en.getValue()[1], en.getValue()[0]));
        }
        print("IMPORT-ORDER", importOrder);
        print("ACCEPTED", accepted);
        print("DIFFER", differ);
        print("MISSING", missing);
        print("EXTRA", extra);
        return differ.size() + missing.size() + extra.size();
    }

    private static void print(String label, List<String> items) {
        for (String item : items) System.out.println("  " + label + " " + item);
    }

    /** The kind of artifact a path holds, by the suffix its class name ends in. */
    static String kindOf(String path) {
        String name = path.substring(path.lastIndexOf('/') + 1).replaceAll("\\.\\w+$", "");
        String[] suffixes = {"RepositoryHelper", "Mapper", "SrchDTO", "ResultDTO", "DTO", "Repository",
                "CoreService", "Service", "Controller", "Identity", "Sortable", "Pageable", "Views"};
        for (String s : suffixes) {
            if (name.endsWith(s)) return s;
        }
        if (name.equals("Q") || name.matches("Q[A-Z].*")) return "Q";
        if (path.contains("/enums/")) return "enum";
        if (path.contains("/entity/")) return "entity";
        return "other";
    }

    /** Files carrying the generated-file header: the ones the extractor owns. */
    private static Map<String, String> generatedFiles(File root) throws IOException {
        Map<String, String> all = readAll(root);
        Map<String, String> out = new TreeMap<String, String>();
        for (Map.Entry<String, String> en : all.entrySet()) {
            if (en.getValue().startsWith(HEADER)) out.put(en.getKey(), en.getValue());
        }
        return out;
    }

    private static Map<String, String> readAll(File root) throws IOException {
        Map<String, String> out = new TreeMap<String, String>();
        collect(root, root, out);
        return out;
    }

    private static void collect(File root, File dir, Map<String, String> out) throws IOException {
        File[] list = dir.listFiles();
        if (list == null) return;
        for (File f : list) {
            if (f.isDirectory()) {
                collect(root, f, out);
            } else {
                String rel = root.toURI().relativize(f.toURI()).getPath();
                out.put(rel, new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8));
            }
        }
    }

    /** The text without the hash header, line endings or trailing blanks. */
    static String normalize(String text) {
        StringBuilder sb = new StringBuilder();
        for (String line : text.replace("\r\n", "\n").split("\n", -1)) {
            if (line.startsWith(HEADER)) continue;
            // The generated-once marker has been written with three different
            // dashes over the years; the file is the user's either way.
            if (line.startsWith(MARKER)) line = MARKER;
            sb.append(line.replaceAll("\\s+$", "")).append('\n');
        }
        return sb.toString().trim();
    }

    /** The normalized text with its import lines sorted. */
    static String sortedImports(String text) {
        List<String> imports = new ArrayList<String>();
        StringBuilder rest = new StringBuilder();
        for (String line : normalize(text).split("\n", -1)) {
            if (line.startsWith("import ")) imports.add(line); else rest.append(line).append('\n');
        }
        Collections.sort(imports);
        return imports + "\n" + rest;
    }

    private static String firstDifference(String a, String b) {
        String[] x = normalize(a).split("\n", -1);
        String[] y = normalize(b).split("\n", -1);
        int n = Math.min(x.length, y.length);
        for (int i = 0; i < n; i++) {
            if (!x[i].equals(y[i])) {
                return "\n      2.x: " + x[i].trim() + "\n      v3 : " + y[i].trim();
            }
        }
        return "\n      (" + x.length + " vs " + y.length + " lines)";
    }
}
