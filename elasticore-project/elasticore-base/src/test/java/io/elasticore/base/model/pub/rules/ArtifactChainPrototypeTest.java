    // ------------------------------------------------------------------
    // helpers
    // ------------------------------------------------------------------

    private static final String MARKER = "Initially generated by ElastiCORE";

    /**
     * Line-by-line equality. When markerException is true, lines containing
     * the generated-once marker text may differ (the golden predates a
     * template comment revision) but both sides must carry the marker.
     */
    private void assertLinesEqual(List<String> expected, List<String> actual, boolean markerException) {
        List<String> exp = stripTrailingBlankLines(expected);
        List<String> act = stripTrailingBlankLines(actual);
        assertEquals(exp.size(), act.size(),
                "line count differs\n--- expected ---\n" + String.join("\n", exp)
                        + "\n--- actual ---\n" + String.join("\n", act));
        for (int i = 0; i < exp.size(); i++) {
            String e = exp.get(i);
            String a = act.get(i);
            if (markerException && e.contains(MARKER)) {
                assertTrue(a.contains(MARKER), "line " + (i + 1) + " must carry marker: " + a);
                continue;
            }
            assertEquals(e, a, "line " + (i + 1) + " differs");
        }
    }

    /** From the first line whose trim equals startToken to before the final brace. */
    private String extractTabBlock(File src, String startToken) throws IOException {
        List<String> lines = readLines(src);
        int start = -1;
        int end = -1;
        for (int i = 0; i < lines.size(); i++) {
            String t = lines.get(i).trim();
            if (start < 0 && t.startsWith(startToken)) start = i;
            if (t.equals("}")) end = i;
        }
        assertTrue(start > 0 && end > start, "block not found in " + src);
        StringBuilder sb = new StringBuilder();
        for (int i = start; i < end; i++) {
            String line = lines.get(i);
            if (line.startsWith("\t")) line = line.substring(1);
            if (line.trim().isEmpty()) line = "";
            sb.append(line).append('\n');
        }
        return sb.toString();
    }

    private String stripTrailingBlanks(String s) {
        return s.replaceAll("[\\n\\s]+$", "") + "\n";
    }

    private List<String> stripTrailingBlankLines(List<String> lines) {
        List<String> r = new ArrayList<String>(lines);
        while (!r.isEmpty() && r.get(r.size() - 1).trim().isEmpty()) {
            r.remove(r.size() - 1);
        }
        return r;
    }

    private List<String> toLines(String text) {
        return new ArrayList<String>(Arrays.asList(text.replace("\r\n", "\n").split("\n", -1)));
    }

    private File golden(String relative) {
        String[] candidates = {
                "../" + GEN_ROOT + relative,
                "elasticore-project/" + GEN_ROOT + relative,
        };
        for (String c : candidates) {
            File f = new File(c);
            if (f.isFile()) return f;
        }
        throw new IllegalStateException("Golden file not found: " + relative
                + " from cwd " + new File(".").getAbsolutePath());
    }

    private List<String> readLines(File f) throws IOException {
        List<String> lines = new ArrayList<String>();
        BufferedReader r = new BufferedReader(
                new InputStreamReader(new FileInputStream(f), StandardCharsets.UTF_8));
        try {
            String line;
            while ((line = r.readLine()) != null) lines.add(line);
        } finally {
            r.close();
        }
        return lines;
    }
