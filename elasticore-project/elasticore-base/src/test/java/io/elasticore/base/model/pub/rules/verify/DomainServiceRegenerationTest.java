package io.elasticore.base.model.pub.rules.verify;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The DSL is where a change is made, also after the developer has written
 * into a process manager or a domain service.
 *
 * Generated once, edited by hand, then the DSL changes: an event is added to
 * 'on' and an aggregate to 'uses'. The regenerated base takes the change - a
 * new listener, its abstract handle(...), a new port - and the developer's
 * class is left exactly as they wrote it, so the compiler names what it still
 * has to write instead of the step being silently absent.
 */
public class DomainServiceRegenerationTest {

    private static File project;
    private static String pmBefore;
    private static String svcBefore;
    /** What the last generation printed. */
    private static String log = "";

    /** A domain service written before the split: its own constructor, extending nothing. */
    private static final String OLD_STYLE = String.join("\n",
            "//ecd:-1H20260101000000_V3.0",
            "// Initially generated by ElastiCORE; no longer managed - do not remove this line.",
            "package io.acme.shop.domain.service;",
            "",
            "public class ShippingDomainService {",
            "    public ShippingDomainService() {",
            "    }",
            "}",
            "");

    private static final String ENV = String.join("\n",
            "elasticore:",
            "  enable: true",
            "  config:",
            "    domainName: shop",
            "    framework: springboot",
            "    mode: jpa",
            "    j2ee: jakarta",
            "  namespace:",
            "    base: io.acme.shop",
            "");

    private static String model(String on, String uses) {
        return String.join("\n",
                "entity:",
                "  Customer:",
                "    meta: entity @root @expose(20)",
                "    fields:",
                "      customerId: long @id @sequence",
                "      orders:     int",
                "  Order:",
                "    meta: entity @root @expose(20) @event(Placed, Cancelled)",
                "    fields:",
                "      orderId: long @id @sequence",
                "processManager:",
                "  Loyalty:",
                "    on: [" + on + "]",
                "    uses: [" + uses + "]",
                "domainService:",
                "  Pricing:",
                "    uses: [" + uses + "]",
                "  Shipping:",
                "    uses: [Customer, Order]",
                "");
    }

    private static void write(String model) throws Exception {
        File dir = new File(project, "src/main/resources/blueprint/shop");
        new File(dir, "model").mkdirs();
        Files.write(new File(dir, "env.yml").toPath(), ENV.getBytes(StandardCharsets.UTF_8));
        Files.write(new File(dir, "model/model.yml").toPath(), model.getBytes(StandardCharsets.UTF_8));
    }

    private static void generate() {
        String[] keys = {"elasticore.base.path", "elasticore.architecture", "elasticore.language"};
        String[] saved = new String[keys.length];
        for (int i = 0; i < keys.length; i++) saved[i] = System.getProperty(keys[i]);
        try {
            System.setProperty("elasticore.base.path", project.getAbsolutePath());
            System.setProperty("elasticore.architecture", "hexagonal");
            System.setProperty("elasticore.language", "java");
            java.io.PrintStream out = System.out;
            java.io.ByteArrayOutputStream captured = new java.io.ByteArrayOutputStream();
            try {
                System.setOut(new java.io.PrintStream(captured, true, "UTF-8"));
                RulesGenRunner.main(new String[0]);
            } catch (java.io.UnsupportedEncodingException e) {
                throw new IllegalStateException(e);
            } finally {
                System.setOut(out);
            }
            log = new String(captured.toByteArray(), StandardCharsets.UTF_8);
            out.print(log);
        } finally {
            for (int i = 0; i < keys.length; i++) {
                if (saved[i] == null) System.clearProperty(keys[i]);
                else System.setProperty(keys[i], saved[i]);
            }
        }
    }

    private static File java(String pkg, String className) {
        return new File(project, "src/main/java/io/acme/shop/" + pkg + "/" + className + ".java");
    }

    private static String read(File f) throws Exception {
        assertTrue(f.exists(), "not generated: " + f);
        return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8);
    }

    @BeforeAll
    static void generateEditChangeRegenerate() throws Exception {
        project = Files.createTempDirectory("elcore-regen").toFile();
        write(model("OrderPlaced", "Customer"));
        File old = java("domain/service", "ShippingDomainService");
        old.getParentFile().mkdirs();
        Files.write(old.toPath(), OLD_STYLE.getBytes(StandardCharsets.UTF_8));
        generate();

        // The developer writes the step and the operation.
        File pm = java("application", "LoyaltyProcessManager");
        pmBefore = read(pm).replace("// The next step goes here.", "customerRepositoryPort.findById(1L); // mine");
        Files.write(pm.toPath(), pmBefore.getBytes(StandardCharsets.UTF_8));
        File svc = java("domain/service", "PricingDomainService");
        svcBefore = read(svc).replace("// This file is written once", "// mine. This file is written once");
        Files.write(svc.toPath(), svcBefore.getBytes(StandardCharsets.UTF_8));

        // Then the model changes.
        // OrderCancelled added, OrderPlaced removed.
        write(model("OrderCancelled", "Customer, Order"));
        generate();
    }

    @Test
    public void anEventRemovedFromOnLeavesTheDevelopersHandleOverridingNothing() throws Exception {
        String base = read(java("application", "LoyaltyProcessManagerBase"));
        assertFalse(base.contains("OrderPlacedEvent"), base);
        String mine = read(java("application", "LoyaltyProcessManager"));
        assertTrue(mine.contains("@Override") && mine.contains("handle(OrderPlacedEvent event)"),
                "kept as written - its @Override now overrides nothing, which the compiler says: " + mine);
    }

    @Test
    public void aFileWrittenBeforeTheSplitIsToldToExtendItsBase() throws Exception {
        assertEquals(OLD_STYLE, read(java("domain/service", "ShippingDomainService")), "the developer's file is kept");
        assertTrue(read(java("domain/service", "ShippingDomainServiceBase")).contains("protected OrderRepositoryPort"));
        assertTrue(log.contains("does not extend ShippingDomainServiceBase, which is regenerated from the DSL"), log);
    }

    @AfterAll
    static void clean() throws Exception {
        java.lang.reflect.Field tmp = io.elasticore.base.model.core.BaseECoreModelContext.class.getDeclaredField("tmpCtx");
        tmp.setAccessible(true);
        tmp.set(null, null);
        SpecFactory.valueObjectsInDto(false);
        SpecFactory.rootsSplitByDefault(false);
        SpecFactory.commandOnlyRoots(false);
        if (project == null || !project.exists()) return;
        Files.walkFileTree(project.toPath(), new SimpleFileVisitor<Path>() {
            @Override
            public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) throws java.io.IOException {
                Files.delete(file);
                return FileVisitResult.CONTINUE;
            }

            @Override
            public FileVisitResult postVisitDirectory(Path dir, java.io.IOException e) throws java.io.IOException {
                Files.delete(dir);
                return FileVisitResult.CONTINUE;
            }
        });
    }

    @Test
    public void anEventAddedToOnReachesTheBaseAndTheCompilerAsksForItsStep() throws Exception {
        String base = read(java("application", "LoyaltyProcessManagerBase"));
        assertTrue(base.contains("public void on(OrderCancelledEvent event) {"), base);
        assertTrue(base.contains("protected abstract void handle(OrderCancelledEvent event);"), base);
        assertTrue(base.contains("protected OrderRepositoryPort orderRepositoryPort;"), "a name added to uses: " + base);

        String mine = read(java("application", "LoyaltyProcessManager"));
        assertEquals(pmBefore, mine, "the developer's class is left as they wrote it");
        assertFalse(mine.contains("OrderCancelledEvent"),
                "so it does not implement handle(OrderCancelledEvent) - the compiler says so, by name");
    }

    @Test
    public void aNameAddedToUsesIsAPortOfTheBaseWithNoEditToTheService() throws Exception {
        String base = read(java("domain/service", "PricingDomainServiceBase"));
        assertTrue(base.contains("protected CustomerRepositoryPort customerRepositoryPort;"), base);
        assertTrue(base.contains("protected OrderRepositoryPort orderRepositoryPort;"), base);
        assertEquals(svcBefore, read(java("domain/service", "PricingDomainService")));
    }
}
