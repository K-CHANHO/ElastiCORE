package io.elasticore.base.model.loader.module;

import io.elasticore.base.model.core.Items;
import io.elasticore.base.model.dto.DataTransfer;
import io.elasticore.base.model.entity.EntityAnnotation;
import io.elasticore.base.model.loader.ModelLoaderContext;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.LinkedHashMap;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Regression test for the DTO identity-collision precedence rule in
 * {@link DataTransferModelLoader#loadModel(ModelLoaderContext, Items, java.util.Map)}.
 *
 * <p>When an {@code @expose}/{@code @service} entity auto-generates a DTO named
 * {@code {Entity}SrchDTO} / {@code {Entity}DTO}, and the user has hand-declared a DTO
 * of the same name, the explicitly-declared DTO MUST win regardless of load order.
 * Auto-generated DTOs carry the {@code @autogen} marker; explicit declarations do not.
 *
 * <p>Before the fix, registration was "first-registered wins", so the auto-generated
 * DTO could shadow the user's declaration and drop its declared fields.
 */
@DisplayName("DTO declaration precedence over auto-generated DTO")
class DtoDeclarationPrecedenceTest {

    private static final String DOMAIN = "testDomain";
    private static final String DTO_NAME = "VendorInfoSrchDTO";

    /** Build a single-entry dto map: name -> { meta, fields }. */
    private LinkedHashMap<String, LinkedHashMap> dtoMap(String meta, LinkedHashMap<String, Object> fields) {
        LinkedHashMap<String, Object> body = new LinkedHashMap<>();
        body.put("meta", meta);
        if (fields != null) {
            body.put("fields", fields);
        }
        LinkedHashMap<String, LinkedHashMap> map = new LinkedHashMap<>();
        map.put(DTO_NAME, (LinkedHashMap) body);
        return map;
    }

    private LinkedHashMap<String, Object> explicitFields() {
        LinkedHashMap<String, Object> fields = new LinkedHashMap<>();
        fields.put("vendorCdNm", "string");
        return fields;
    }

    /** Simulates the auto-generated DTO: carries the @autogen marker and entity-derived fields. */
    private LinkedHashMap<String, LinkedHashMap> autoGeneratedMap() {
        LinkedHashMap<String, Object> fields = new LinkedHashMap<>();
        fields.put("companyId", "string");
        fields.put("vendorId", "string");
        return dtoMap("dto @" + EntityAnnotation.AUTOGENERATED + " @searchable(entity=VendorInfo)", fields);
    }

    /** Simulates the user's hand-declared DTO: no @autogen marker, custom field list. */
    private LinkedHashMap<String, LinkedHashMap> explicitMap() {
        return dtoMap("dto @searchable(entity=VendorInfo, pageable=true)", explicitFields());
    }

    private DataTransfer loadAndFind(LinkedHashMap<String, LinkedHashMap> first,
                                     LinkedHashMap<String, LinkedHashMap> second) {
        ModelLoaderContext ctx = ModelLoaderContext.createForRuntime(DOMAIN, null);
        Items<DataTransfer> items = ctx.getDataTransferItems();
        DataTransferModelLoader loader = new DataTransferModelLoader();

        loader.loadModel(ctx, items, first);
        loader.loadModel(ctx, items, second);

        return items.findByName(DTO_NAME);
    }

    @Test
    @DisplayName("Explicit declaration loaded AFTER auto-generated one replaces it")
    void explicitWinsWhenLoadedSecond() {
        DataTransfer survivor = loadAndFind(autoGeneratedMap(), explicitMap());

        assertNotNull(survivor, "VendorInfoSrchDTO must exist");
        assertFalse(survivor.getMetaInfo().hasMetaAnnotation(EntityAnnotation.AUTOGENERATED),
                "Surviving DTO must be the explicit declaration (no @autogen marker)");
        assertNotNull(survivor.findFieldName("vendorCdNm"),
                "Explicit DTO's declared field 'vendorCdNm' must be retained");
    }

    @Test
    @DisplayName("Explicit declaration loaded BEFORE auto-generated one is kept")
    void explicitWinsWhenLoadedFirst() {
        DataTransfer survivor = loadAndFind(explicitMap(), autoGeneratedMap());

        assertNotNull(survivor, "VendorInfoSrchDTO must exist");
        assertFalse(survivor.getMetaInfo().hasMetaAnnotation(EntityAnnotation.AUTOGENERATED),
                "Auto-generated DTO must NOT overwrite the explicit declaration");
        assertNotNull(survivor.findFieldName("vendorCdNm"),
                "Explicit DTO's declared field 'vendorCdNm' must be retained");
    }
}
