package io.elasticore.base.model.pub.rules.verify;

import org.junit.jupiter.api.Test;

import java.util.Arrays;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * What the runner may still do to a file the developer owns: rewrite an
 * extension nobody edited when its constructor went stale, and keep an owned
 * entity's table annotations in step with the DSL - nothing else.
 */
public class OwnedFileRepairTest {

    private static final String JAVA_OLD =
            "// Initially generated by ElastiCORE; no longer managed - do not remove this line.\n"
            + "package a;\n\nimport a.ShopRepositoryHelper;\n\n@Service\n"
            + "public class OrderService extends OrderCoreService {\n\n"
            + "    public OrderService(ShopRepositoryHelper helper) {\n        super(helper);\n    }\n}\n";
    private static final String JAVA_NEW =
            "// Initially generated by ElastiCORE; no longer managed - do not remove this line.\n"
            + "package a;\n\nimport a.OrderRepositoryPort;\n\n@Service\n"
            + "public class OrderService extends OrderCoreService {\n\n"
            + "    public OrderService(OrderRepositoryPort repository, OrderQueryPort query, EntityManager entityManager) {\n"
            + "        super(repository, query, entityManager);\n    }\n}\n";

    @Test
    public void anOwnedFileNobodyTouchedIsKnownByItsHash() {
        io.elasticore.base.util.HashUtils.Response untouched = io.elasticore.base.util.HashUtils.checkContentModified(
                new java.io.StringReader(io.elasticore.base.util.HashUtils.makeEcdCode(JAVA_OLD) + JAVA_OLD));
        assertEquals(io.elasticore.base.util.HashUtils.UNTRACKED, untouched.getStatus());
        assertTrue(RulesGenRunner.neverEdited(untouched), "still what the generator wrote");

        String edited = JAVA_OLD.replace("    }\n}\n", "    }\n\n    public void confirm() { }\n}\n");
        io.elasticore.base.util.HashUtils.Response mine = io.elasticore.base.util.HashUtils.checkContentModified(
                new java.io.StringReader(io.elasticore.base.util.HashUtils.makeEcdCode(JAVA_OLD) + edited));
        assertFalse(RulesGenRunner.neverEdited(mine), "one edit makes it the developer's");
    }

    @Test
    public void aDependencyOrAStatementTheDeveloperAddedKeepsTheFileTheirs() {
        String extraParam = JAVA_OLD.replace("public OrderService(ShopRepositoryHelper helper) {",
                "public OrderService(ShopRepositoryHelper helper, Clock clock) {");
        assertFalse(RulesGenRunner.untouchedApartFromWiring(extraParam, JAVA_NEW, "OrderService"));
        String extraStatement = JAVA_OLD.replace("        super(helper);\n", "        super(helper);\n        warmUp();\n");
        assertFalse(RulesGenRunner.untouchedApartFromWiring(extraStatement, JAVA_NEW, "OrderService"));
        String kotlinExtra = "package a\n\nopen class OrderService(\n    helper: ShopRepositoryHelper,\n    private val clock: Clock\n"
                + ") : OrderCoreService(helper), OrderUseCase {\n}\n";
        String kotlinNow = "package a\n\nopen class OrderService(\n    repository: OrderRepositoryPort\n"
                + ") : OrderCoreService(repository), OrderUseCase {\n}\n";
        assertFalse(RulesGenRunner.untouchedApartFromWiring(kotlinExtra, kotlinNow, "OrderService"));
    }

    @Test
    public void aSyncedFileKeepsAStampThatNoLongerMatchesIt() {
        // The file keeps its old stamp after the annotations are brought in
        // line, so it never reads as untouched generator output afterwards.
        String generated = "// Initially generated by ElastiCORE; no longer managed - do not remove this line.\n"
                + "package a;\n\n@Entity\n@Table(name = \"t_old\")\npublic class A extends ABase {\n\n}\n";
        String edited = generated.replace("public class A extends ABase {\n\n}", "public class A extends ABase {\n    void go() { }\n}");
        String synced = RulesGenRunner.withClassAnnotations(io.elasticore.base.util.HashUtils.makeEcdCode(generated) + edited,
                generated.replace("t_old", "t_new"), "A",
                java.util.Arrays.asList("@Entity", "@Table(name = \"t_new\")"));
        io.elasticore.base.util.HashUtils.Response st = io.elasticore.base.util.HashUtils.checkContentModified(
                new java.io.StringReader(io.elasticore.base.util.HashUtils.makeEcdCode(generated) + synced));
        assertFalse(RulesGenRunner.neverEdited(st), "the developer's go() must not be taken for generated code");
        assertTrue(synced.contains("void go()") && synced.contains("t_new"), synced);
    }

    @Test
    public void anUneditedJavaExtensionMayBeWrittenAgain() {
        assertTrue(RulesGenRunner.untouchedApartFromWiring(JAVA_OLD, JAVA_NEW, "OrderService"));
    }

    @Test
    public void anEditedOneMayNot() {
        String edited = JAVA_OLD.replace("    }\n}\n", "    }\n\n    public void confirm() { }\n}\n");
        assertFalse(RulesGenRunner.untouchedApartFromWiring(edited, JAVA_NEW, "OrderService"));
    }

    @Test
    public void anUneditedKotlinExtensionMayBeWrittenAgain() {
        String old = "package a\n\n@Service\nopen class OrderService(\n    helper: ShopRepositoryHelper\n"
                + ") : OrderCoreService(helper), OrderUseCase {\n}\n";
        String now = "package a\n\n@Service\nopen class OrderService(\n    repository: OrderRepositoryPort,\n"
                + "    query: OrderQueryPort\n) : OrderCoreService(repository, query), OrderUseCase {\n}\n";
        assertTrue(RulesGenRunner.untouchedApartFromWiring(old, now, "OrderService"));
        String edited = old.replace("{\n}\n", "{\n    fun confirm() {}\n}\n");
        assertFalse(RulesGenRunner.untouchedApartFromWiring(edited, now, "OrderService"));
    }

    @Test
    public void tableAnnotationsFollowTheDslAndTheDevelopersStay() {
        String owned = "// Initially generated by ElastiCORE; no longer managed - do not remove this line.\n"
                + "package a;\n\nimport jakarta.persistence.Entity;\nimport jakarta.persistence.Table;\n\n"
                + "/** doc */\n@Entity\n@Table(name = \"erp_so\")\n@MyMarker\n"
                + "public class SalesOrder extends SalesOrderBase {\n\n    public void confirm() { }\n}\n";
        String would = "package a;\n\nimport jakarta.persistence.Entity;\nimport jakarta.persistence.Table;\n"
                + "import org.hibernate.annotations.DynamicUpdate;\n\n@Entity\n@Table(name = \"erp_sales_order\")\n"
                + "@DynamicUpdate\npublic class SalesOrder extends SalesOrderBase {\n\n}\n";

        String synced = RulesGenRunner.withClassAnnotations(owned, would, "SalesOrder",
                Arrays.asList("@Entity", "@Table(name = \"erp_sales_order\")", "@DynamicUpdate"));

        assertTrue(synced.contains("@Table(name = \"erp_sales_order\")\n@DynamicUpdate\n@MyMarker\npublic class SalesOrder"), synced);
        assertFalse(synced.contains("erp_so\""), synced);
        assertTrue(synced.contains("import org.hibernate.annotations.DynamicUpdate;"), synced);
        assertTrue(synced.contains("public void confirm() { }"), "the behaviour is untouched: " + synced);
        assertEquals(1, synced.split("import jakarta.persistence.Entity;", -1).length - 1, synced);
    }

    @Test
    public void aMultiLineAnnotationIsLeftForTheDeveloper() {
        String owned = "package a;\n\n@Entity\n@Table(name = \"x\",\n    indexes = {})\npublic class A extends ABase {\n}\n";
        assertNull(RulesGenRunner.withClassAnnotations(owned, "package a;\n", "A", Arrays.asList("@Entity")));
    }
}
